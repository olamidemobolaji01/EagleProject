const SVG_OPEN =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ' +
  'stroke="currentColor" stroke-width="2" stroke-linecap="round" ' +
  'stroke-linejoin="round" aria-hidden="true" focusable="false"';

export function iconSvg(name, className = 'icon') {
  const glyph = GLYPHS[name];
  if (!glyph) return '';
  return `${SVG_OPEN} class="${className}" data-icon="${name}">${glyph}</svg>`;
}

export function hydrateIcons(root = document) {
  const slots = root.querySelectorAll('i[data-icon]');
  const template = document.createElement('template');

  for (const slot of slots) {
    const name = slot.dataset.icon;

    if (!GLYPHS[name]) {
      slot.dataset.iconMissing = '';
      continue;
    }

    const className = slot.className ? `icon ${slot.className}` : 'icon';
    template.innerHTML = iconSvg(name, className);
    slot.replaceWith(template.content.firstElementChild);
  }
}

